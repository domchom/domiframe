/** The text as rows of "#" (ink) and "." (none), or null if a letter isn't drawn here. */
export function layout(text) {
  if ([...text].some((c) => !(c in GLYPHS))) return null;
  const out = Array(CAP).fill("");
  [...text].forEach((c, n) => GLYPHS[c].forEach((r, y) => (out[y] += (n ? ".".repeat(SPACING) : "") + r)));
  return out;
}
